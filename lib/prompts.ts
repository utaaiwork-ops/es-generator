/** ES種類に応じた専門家ロール + 共通ルールを返す */
export function getSystemPrompt(esType: string): string {
  const role = ROLE_PROMPTS[esType] ?? DEFAULT_ROLE
  return role + COMMON_RULES
}

/** プロフィール・企業情報からユーザープロンプトを組み立てる */
export function buildUserPrompt(
  profile: Record<string, string>,
  companyInfo: string,
  esType: string,
  charLimit: number,
  customQuestion?: string | null,
): string {
  // プロフィール整形
  const profileText = Object.entries(profile)
    .filter(([, value]) => value)
    .map(([key, value]) => `- ${key}: ${value}`)
    .join("\n")

  // ES項目名の決定
  let esLabel: string
  let typeGuide: string

  if (customQuestion) {
    esLabel = customQuestion
    typeGuide = `質問「${customQuestion}」に対する回答を、結論ファースト・PREP法で構成してください。`
  } else {
    esLabel = ES_TYPES[esType] ?? esType
    typeGuide = TYPE_GUIDES[esType] ?? "結論ファースト・PREP法で構成してください。"
  }

  const goalMin = Math.floor(charLimit * 0.95)
  const goalMax = Math.floor(charLimit * 1.05)

  return `【学生のプロフィール】
${profileText}

【企業情報】
${companyInfo}

${typeGuide}

【指示】
上記の学生のプロフィールと企業情報を踏まえ、この企業に刺さる「${esLabel}」を作成してください。

【文字数について】★最重要★
- 目標: ${goalMin}〜${goalMax}字（制限字数ギリギリまで使い切ること）
- 短すぎるのはNG。${charLimit}字の制限をフル活用し、内容を充実させること
- 少し超える分には問題ない。足りないよりは多い方が良い
- 句読点・括弧も1字としてカウントすること

【重要な注意】
- プロフィールに書かれた事実・経験のみを使うこと。存在しないエピソードを捏造しない
- プロフィールの情報が薄い場合は、ある情報を最大限活かして書く
- 企業情報から、その企業ならではの特徴（事業・理念・強み）を必ず盛り込む

【出力形式】
- ES本文のみを出力してください（前置きや説明は不要）
- 改行は入れず、1つの段落として出力すること`
}
