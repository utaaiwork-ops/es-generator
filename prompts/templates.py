ES_TYPES = {
    "志望動機": "この企業への志望動機",
    "ガクチカ": "学生時代に力を入れたこと（ガクチカ）",
    "自己PR": "自己PR",
    "強み・弱み": "自分の強み・弱み",
    "将来やりたいこと": "入社後・将来やりたいこと",
}


def build_user_prompt(
    profile: dict[str, str],
    company_info: str,
    es_type: str,
    char_limit: int,
    custom_question: str | None = None,
) -> str:
    """プロフィール・企業情報からユーザープロンプトを組み立てる。"""

    # プロフィール整形
    profile_text = "\n".join(
        f"- {key}: {value}" for key, value in profile.items() if value
    )

    # ES項目名の決定
    if custom_question:
        es_label = custom_question
        type_guide = f"質問「{custom_question}」に対する回答を、結論ファースト・PREP法で構成してください。"
    else:
        es_label = ES_TYPES.get(es_type, es_type)
        type_guide = TYPE_GUIDES.get(es_type, "結論ファースト・PREP法で構成してください。")

    return f"""\
【学生のプロフィール】
{profile_text}

【企業情報】
{company_info}

{type_guide}

【指示】
上記の学生のプロフィールと企業情報を踏まえ、この企業に刺さる「{es_label}」を{char_limit}字以内で作成してください。

【重要な注意】
- プロフィールに書かれた事実・経験のみを使うこと。存在しないエピソードを捏造しない
- プロフィールの情報が薄い場合は、ある情報を最大限活かして書く
- 企業情報から、その企業ならではの特徴（事業・理念・強み）を必ず盛り込む
- 指定文字数の90〜100%に収める（{int(char_limit * 0.9)}〜{char_limit}字が理想）

【出力形式】
- ES本文のみを出力してください（前置きや説明は不要）
"""
